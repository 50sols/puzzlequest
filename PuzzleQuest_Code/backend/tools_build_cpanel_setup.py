#!/usr/bin/env python3
"""Developer-only packaging helper for the approved cPanel fixed-subdomain layout.

Does NOT run on production hosting and does NOT create a database or .env.
The browser installer at public/install/index.php performs the web setup.
"""
from __future__ import annotations
import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parent
PUBLIC = 'public_html/puzzlequest.50sols.com/'
PRIVATE = 'puzzlequest_app/'
EXCLUDED_DIRS = {'.git', '.tools', '.idea', '.vscode', 'node_modules', '__pycache__'}
EXCLUDED_ROOT = {'.phpunit.result.cache', 'AGENTS.md', 'CLAUDE.md', 'phpunit.xml', 'package.json', 'package-lock.json', 'vite.config.js',
                 '.npmrc', '.gitignore', '.gitattributes', '.editorconfig',
                 'SOURCE_SHA256SUMS.txt', 'SHA256SUMS.txt', 'BUILD_INFO.json',
                 'SETUP_MANIFEST.json', 'TEST_RESULTS.json', 'tools_build_cpanel_setup.py'}
FORBIDDEN = {'.env', '.env.installing', 'install.key', 'installed.lock'}


def accepted(rel: Path) -> bool:
    bits = rel.parts
    if not bits or any(x in EXCLUDED_DIRS for x in bits): return False
    if any(x in FORBIDDEN for x in bits): return False
    if any(x.startswith('.env.') and x != '.env.example' for x in bits): return False
    if bits[0] in {'tests', 'public'}: return False
    if bits[0] in {'storage'}:
        # Keep placeholders, not live app storage, cached views, queue data or logs.
        return rel.name == '.gitignore'
    if bits[0] == 'bootstrap' and 'cache' in bits:
        return rel.name == '.gitignore'
    if len(bits) == 1 and bits[0] in EXCLUDED_ROOT: return False
    if rel.suffix.lower() in {'.pem', '.p8', '.p12', '.pfx', '.key', '.sqlite', '.db', '.ttf', '.otf', '.woff', '.woff2', '.eot'}: return False
    if rel.name.endswith('.log'): return False
    return True


def pack(output: Path) -> None:
    if not (ROOT/'vendor/autoload.php').is_file():
        raise SystemExit('Missing production vendor dependencies in source; cannot build one-ZIP setup')
    if not (ROOT/'packaging/cpanel_templates/index.php').is_file():
        raise SystemExit('Missing approved cPanel index template')
    if not (ROOT/'packaging/cpanel_templates/install/index.php').is_file():
        raise SystemExit('Missing approved cPanel web-installer template')
    if not (ROOT/'public/install/wizard.js').is_file():
        raise SystemExit('Missing web-installer assets')
    payload: dict[str, bytes] = {}
    for path in ROOT.rglob('*'):
        if path.is_symlink() or not path.is_file(): continue
        rel=path.relative_to(ROOT)
        if rel.parts[0] == 'packaging': continue
        if rel.parts[0] == 'public':
            if rel.name in FORBIDDEN or any(x in FORBIDDEN for x in rel.parts) or rel.suffix.lower() in {'.ttf', '.otf', '.woff', '.woff2', '.eot'}: continue
            if rel.as_posix() in {'index.php','install/index.php'}: continue
            payload[PUBLIC + Path(*rel.parts[1:]).as_posix()] = path.read_bytes()
        elif accepted(rel):
            payload[PRIVATE + rel.as_posix()] = path.read_bytes()
    # Use fixed-subdomain entrypoints (source-mode public/index.php is deliberately different).
    payload[PUBLIC+'index.php'] = (ROOT/'packaging/cpanel_templates/index.php').read_bytes()
    payload[PUBLIC+'install/index.php'] = (ROOT/'packaging/cpanel_templates/install/index.php').read_bytes()
    manifest = {
        'product': 'PuzzleQuest',
        'distribution': 'cPanel fixed subdomain clean install (developer build)',
        'release_label': 'v1.0.0-subdomain',
        'document_root': '/home/ACCOUNT/public_html/puzzlequest.50sols.com',
        'private_directory': '/home/ACCOUNT/puzzlequest_app',
        'install_url': 'https://puzzlequest.50sols.com/install/',
        'git_sha': os.environ.get('PUZZLEQUEST_GIT_SHA', 'unknown'),
        'files': len(payload),
        'notes': ['Never extract on top of an installed live site.',
                  'Database configuration and APP_KEY are generated by the web installer.',
                  'No production DB/install/upgrade test is implied by packaging.'],
    }
    payload[PRIVATE+'SETUP_MANIFEST.json'] = (json.dumps(manifest, ensure_ascii=False, indent=2)+'\n').encode()
    payload[PRIVATE+'BUILD_INFO.json'] = (json.dumps({
        'source': 'PuzzleQuest_Code/backend modified original handoff',
        'git_sha': os.environ.get('PUZZLEQUEST_GIT_SHA', 'unknown'),
        'release_label': 'v1.0.0-subdomain',
        'build_generated_at_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'tool': 'tools_build_cpanel_setup.py',
        'status': 'Release candidate; MySQL Fresh Install and upgrade not certified',
    },ensure_ascii=False,indent=2)+'\n').encode()
    checksum_text = ''.join(f'{hashlib.sha256(blob).hexdigest()}  {path}\n' for path, blob in sorted(payload.items()))
    payload[PRIVATE+'SHA256SUMS.txt'] = checksum_text.encode()
    output.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(output,'w',zipfile.ZIP_DEFLATED,compresslevel=6,allowZip64=True) as z:
        for name,blob in sorted(payload.items()):
            if name.startswith('/') or '..' in Path(name).parts: raise RuntimeError('Unsafe path')
            entry = zipfile.ZipInfo(name)
            entry.create_system = 3
            entry.external_attr = (0o100644 << 16)  # cPanel/Apache must read public assets.
            entry.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(entry, blob, compress_type=zipfile.ZIP_DEFLATED, compresslevel=6)
    with zipfile.ZipFile(output) as z:
        bad=z.testzip()
        if bad: raise RuntimeError(f'Broken ZIP member: {bad}')
    print(f'Created {output} ({len(payload)} files). No runtime secrets included.')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description='Build a cPanel fixed-subdomain fresh-install ZIP (developer computer only)')
    parser.add_argument('--output',type=Path,default=ROOT.parent.parent.parent/'PuzzleQuest-Setup-v1.0.0.zip')
    args=parser.parse_args()
    pack(args.output.resolve())
