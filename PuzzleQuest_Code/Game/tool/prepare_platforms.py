#!/usr/bin/env python3
"""Finalize Android/iOS runners with the locally installed *official* Flutter SDK.

Do not run on cPanel. The developer's build machine supplies the platform SDK,
Gradle wrapper JAR, Xcode project, and signing assets. Safe to rerun.
"""
from pathlib import Path
import plistlib, re, shutil, subprocess, sys

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = 'com.puzzlequest50sols.com'


def run(*args):
    print('+', ' '.join(map(str, args)), flush=True)
    subprocess.run(list(args), cwd=ROOT, check=True)


def install_ios_resource():
    """Register GoogleService-Info.plist in Runner's Copy Bundle Resources.

    Use the xcodeproj CocoaPods dependency on macOS rather than corrupting
    project.pbxproj by ad-hoc string substitution.
    """
    project = ROOT / 'ios/Runner.xcodeproj'
    if not project.exists():
        raise RuntimeError('Flutter create did not generate iOS Runner.xcodeproj')
    ruby = r'''
require 'xcodeproj'
project = Xcodeproj::Project.open('ios/Runner.xcodeproj')
target = project.targets.find { |t| t.name == 'Runner' }
raise 'Runner target missing' unless target
file = project.files.find { |f| f.path == 'GoogleService-Info.plist' }
file ||= project.main_group.find_subpath('Runner', true).new_file('GoogleService-Info.plist')
unless target.resources_build_phase.files_references.include?(file)
  target.resources_build_phase.add_file_reference(file)
end
project.build_configurations.each do |config|
  config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '15.0'
end
target.build_configurations.each do |config|
  config.build_settings['PRODUCT_BUNDLE_IDENTIFIER'] = 'com.puzzlequest50sols.com'
  config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '15.0'
end
project.save
'''
    ruby_exe = shutil.which('ruby')
    if ruby_exe is None:
        raise RuntimeError('Ruby/xcodeproj required for iOS Runner; run on macOS with CocoaPods')
    subprocess.run([ruby_exe, '-e', ruby], cwd=ROOT, check=True)


def main():
    # Missing Dart files cause hundreds of secondary analyzer errors.
    # Refuse to prepare runners from a partial Hotfix-only source tree.
    from check_source_integrity import check
    if not check():
        raise SystemExit('Incomplete Game/lib source. Restore the COMPLETE recovery package first.')
    if shutil.which('flutter') is None:
        raise SystemExit('Flutter SDK missing: cannot create/validate native runners here.')
    # Existing Dart source will not be replaced. Flutter fills missing native
    # project pieces with its own version-matched templates.
    # Capture the versioned Android compatibility repairs before Flutter adds
    # platform templates. Reapply them afterward if 'flutter create' rewrites them.
    locked_android = [
        'android/settings.gradle.kts',
        'android/app/build.gradle.kts',
        'android/gradle/wrapper/gradle-wrapper.properties',
    ]
    preserved = {name: (ROOT/name).read_bytes() for name in locked_android
                 if (ROOT/name).is_file()}
    run('flutter', 'create', '--platforms=android,ios', '--project-name=puzzlequest_game', '.')
    for name, content in preserved.items():
        destination = ROOT/name
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or destination.read_bytes() != content:
            destination.write_bytes(content)
            print('Restored PuzzleQuest Android build compatibility:', name)

    android = ROOT / 'android'
    ios = ROOT / 'ios'
    if not (android / 'gradlew').exists() or not (android / 'gradle/wrapper/gradle-wrapper.jar').exists():
        raise RuntimeError('Android Gradle wrapper not generated by Flutter SDK')
    if not (ios / 'Runner.xcodeproj/project.pbxproj').exists():
        raise RuntimeError('iOS Xcode project missing after Flutter SDK platform generation')
    shutil.copy2(ROOT / 'platform_configs/android/google-services.json',
                 android / 'app/google-services.json')
    for directory in (ROOT / 'platform_configs/android/mipmap').glob('mipmap-*'):
        target = android / 'app/src/main/res' / directory.name
        target.mkdir(parents=True, exist_ok=True)
        for icon in directory.glob('*.png'):
            shutil.copy2(icon, target / icon.name)
    shutil.copy2(ROOT / 'platform_configs/ios/GoogleService-Info.plist',
                 ios / 'Runner/GoogleService-Info.plist')
    shutil.copytree(ROOT / 'platform_configs/ios/AppIcon.appiconset',
                    ios / 'Runner/Assets.xcassets/AppIcon.appiconset', dirs_exist_ok=True)
    install_ios_resource()
    # A real Google OAuth native client and associated SHA/APNs config are
    # pending owner/Apple/Google setup; never pretend these are configured.
    print('Platform sources generated and Firebase references copied.')
    print('NEXT: flutter pub get, flutter analyze, flutter test and real device integration tests.')
    print('Native Google OAuth, APNs, production AdMob IDs and signing remain external gates.')


if __name__ == '__main__':
    main()
