#!/usr/bin/env python3
"""Static, non-runtime source/asset audit. It cannot replace flutter analyze/test."""
from pathlib import Path
import json,csv,hashlib,sys,subprocess,re
from PIL import Image
root=Path(__file__).resolve().parents[1]
project=root.parents[1]
checks={}
issues=[]
def check(name,ok,details=''):
    checks[name]={'pass':bool(ok),'details':details}
    if not ok:issues.append(f'{name}: {details}')
level_catalog=json.loads((root/'assets/config/level_catalog.json').read_text())
levels=level_catalog['levels']
counts=[x['selected_piece_count'] for x in levels]
limits=[x['level_time_limit_seconds'] for x in levels]
check('five_published_levels',len(levels)==5 and all(x.get('published_at_launch') for x in levels),str(len(levels)))
check('approved_pieces',counts==[16,16,36,64,100],str(counts))
check('approved_limits',limits==[360,360,600,1080,1800],str(limits))
check('approved_thresholds',[(x['rating_time_thresholds_seconds']['three_stars'],x['rating_time_thresholds_seconds']['two_stars']) for x in levels]==[(150,270),(150,270),(270,450),(480,840),(900,1440)],'Q05-T')
records=0; duplicate_results={}
for entry in levels:
    n=entry['selected_piece_count'];folder=entry['level_folder']
    manifest_path=root/f'assets/puzzles/{folder}/{n}.manifest.v1.json'
    if not manifest_path.exists():issues.append(f'missing manifest {manifest_path}');continue
    manifest=json.loads(manifest_path.read_text())
    ps=manifest['pieces'];records+=len(ps)
    check(f'manifest_{entry["display_code"]}',len(ps)==n and len({p['id'] for p in ps})==n and manifest['difficulty_piece_count']==n, f'{n} pieces')
    hashes={}
    for p in ps:
        ppath=root/f'assets/puzzles/{folder}/{p["image_path"]}'
        if not ppath.is_file():issues.append(f'missing {ppath}');continue
        try:
            with Image.open(ppath) as im: im.verify()
        except Exception as e:issues.append(f'PNG corrupted {ppath}: {e}')
        digest=hashlib.sha256(ppath.read_bytes()).hexdigest()
        hashes.setdefault(digest,[]).append(p['id'])
        if len(p.get('target_rect_px',[]))!=4 or len(p.get('snap_anchor_px',[]))!=2:issues.append(f'invalid {p["id"]} geometry')
    duplicate_results[entry['display_code']]=[e for e in hashes.values() if len(e)>1]
    master=root/f'assets/puzzles/{folder}/master.png'
    if not master.is_file():issues.append(f'missing master {master}')
check('bundled_piece_files_exist',not any('missing ' in issue for issue in issues),'All launch pieces and masters')
check('bundled_piece_images_valid',not any('PNG corrupted ' in issue for issue in issues),'Pillow decode/verify only')
fonts=['Tajawal-Regular.ttf','Tajawal-Medium.ttf','Tajawal-Bold.ttf','Lato-Regular.ttf','Lato-Bold.ttf']
check('font_files',all((root/'assets/fonts'/x).is_file() for x in fonts),', '.join(fonts))
required=[root/'pubspec.yaml',root/'lib/main.dart',root/'lib/game/puzzle_board.dart',root/'lib/game/gameplay.dart',root/'lib/core/api.dart',root/'lib/core/session.dart',root/'lib/core/ads_service.dart',root/'lib/core/push_service.dart']
check('game_source',all(p.is_file() for p in required),'Main, API, gameplay, Flame, Ads, Push')
client=(root/'lib/screens/screens.dart').read_text()
ids=set(map(int,re.findall(r'(?<!\d)(\d+):\[',client)))
check('forty_screen_titles',ids==set(range(1,41)),f'{len(ids)} screen IDs')
check('apple_login_removed','Apple Login' not in client and 'Sign in with Apple' not in client,'Google/Email/Guest only')
check('weekly_only','All-time' not in client and 'All Time' not in client,'Weekly Global only')
check('terms_age_explicit','_acceptedTerms' in client and '_confirmedAge' in client,'Required checkbox states')
check('oauth_native_is_not_falsely_enabled','Google Login (setup pending)' in client,'Native OAuth intentionally gated')
check('firebase_configs',all((root/f'platform_configs/{p}').is_file() for p in ['android/google-services.json','ios/GoogleService-Info.plist']),'Client SDK settings only')
check('native_platform_scaffolding', (root/'tool/prepare_platforms.py').is_file(), 'Runner source is generated by Flutter CLI; no runner binaries delivered')
check('native_android_sources', (root/'android/app/src/main/AndroidManifest.xml').exists() and (root/'android/app/src/main/kotlin/com/puzzlequest50sols/com/MainActivity.kt').exists(), 'Android manifest/Kotlin/Gradle source present')
check('native_ios_sources', (root/'ios/Podfile').exists() and (root/'ios/Runner/AppDelegate.swift').exists() and (root/'ios/Runner/Info.plist').exists(), 'iOS Swift/Podfile/Plist/storyboards present')
check('generated_native_build_projects', (root/'android/gradle/wrapper/gradle-wrapper.jar').exists() and (root/'ios/Runner.xcodeproj/project.pbxproj').exists(), 'Flutter SDK platform generation needed for Gradle wrapper JAR / Xcode PBX project')
check('flutter_sdk_available', bool(subprocess.run(['which','flutter'],capture_output=True).returncode==0),'SDK is mandatory to compile/test')
backend=project/'PuzzleQuest_Code/backend'
# project is PuzzleQuest_Design_Handoff_Updated / PuzzleQuest_Code ??? root.parents[1] = PuzzleQuest_Design_Handoff_Updated ; debug verify
if not backend.exists():backend=root.parent/'backend'
check('backend_exists',backend.exists() and (backend/'routes/api.php').is_file(),str(backend))
if backend.exists():
    game=(backend/'app/Services/Game.php').read_text()
    check('dynamic_manifest_api',"'manifest'=>$v['manifest']" in game,'Catalog exposes revision-pinned piece geometry')
project= root.parent.parent
handoff=project/'PuzzleQuest_Design_FINAL'
design=list((handoff/'01_SCREENS').glob('*/DESIGN.json')) if handoff.exists() else []
check('original_40_screen_handoff',len(design)==40,f'{len(design)} design.json')
check('authenticated_export_and_attachment_source','downloadPrivateZip' in (root/'lib/core/api.dart').read_text() and 'multipartSupport' in (root/'lib/core/api.dart').read_text() and '_downloadExport' in client,'API client handles user data export and optional support image')
check('retryable_piece_journal','postWithKey' in (root/'lib/game/gameplay.dart').read_text() and 'markAcknowledged' in (root/'lib/core/offline_journal.dart').read_text(),'Piece event IDs preserved and retried without new idempotency key')
check('preview_server_checkpoints',"'action':'tick'" in (root/'lib/game/timed_preview.dart').read_text(), 'Foreground time checkpoints to Laravel; pause when unverified')
report={
  'audit_kind':'STATIC_SOURCE_ASSET_VALIDATION_ONLY',
  'status':'STATIC_CHECKS_COMPLETE_NOT_COMPILED',
  'flutter_build_tested':False,'android_tested':False,'ios_tested':False,
  'laravel_runtime_integration_tested':False,
  'bundled_levels':len(levels),'bundled_pieces':records,
  'identical_piece_png_groups_by_level':duplicate_results,
  'checks':checks,'issues':issues,
  'known_release_blockers':[
      'Native Flutter/Dart SDK not available in this container; package resolution/analyze/test/APK/AAB/IPA were not run',
      'Android/iOS native source templates included, but generated Gradle wrapper JAR and Xcode project require Flutter SDK bootstrap',
      'Google OAuth Android/iOS clients and SHA/nonce verification not configured',
      'Production AdMob identifiers and SSV real callback not exercised',
      'FCM service credential/APNs signing and on-device push not tested',
      '100-piece device hit-target/visual assembly/performance QA still required',
      'Live Laravel API and MySQL end-to-end contract tests not executed',
  ]}
(root/'QA_REPORT.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({'passed':sum(1 for x in checks.values() if x['pass']),'checked':len(checks),'issues':len(issues),'duplicates':{k:len(v) for k,v in duplicate_results.items()}},ensure_ascii=False))
for i in issues[:20]:print('ISSUE:',i)
